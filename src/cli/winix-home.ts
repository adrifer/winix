// The per-user Winix installation: a copy of Winix in %LOCALAPPDATA%\Winix
// (Windows) or ~/.local/share/winix (Linux), the `winix` command that runs it,
// and the checkout bootstrap set up on this machine.
//
//   <home>/runtime/<version>/winix.exe        Windows
//   <home>/runtime/<version>/winix(.bin)      Linux: a wrapper and the binary
//   <home>/checkout                           the config directory `winix switch` uses from any folder
//   %LOCALAPPDATA%\Winix\bin\winix.cmd        the command (Windows, on the user PATH)
//   ~/.local/bin/winix                        the command (Linux)
//
// The command always runs `<installed> run <args>`, which picks the Winix to
// run from where you are (see routeRun in commands/bootstrap.ts).

import { chmod, copyFile, lstat, mkdir, readFile, readdir, rename, rm, writeFile } from "node:fs/promises";
import { existsSync, readFileSync } from "node:fs";
import { execFileSync } from "node:child_process";
import { delimiter, dirname, join, resolve } from "node:path";
import { homedir } from "node:os";
import { standaloneRuntime } from "../runtime.ts";

export const GENERATED = "# Generated by Winix bootstrap";
/** The nixpkgs revision the NixOS loader comes from (matches install.sh). */
export const BOOTSTRAP_NIXPKGS = "github:NixOS/nixpkgs/0bb2eedc20e4739f29e8045034f2828ad7054f8f";

export function shellQuote(value: string): string {
  return `'${value.replaceAll("'", "'\\''")}'`;
}

export async function assertPlainDirectories(paths: string[]): Promise<void> {
  for (const path of paths) {
    try {
      if (!(await lstat(path)).isDirectory()) throw new Error(`Refusing a linked/non-directory Winix path: ${path}`);
    } catch (error) {
      if ((error as NodeJS.ErrnoException).code !== "ENOENT") throw error;
    }
  }
}

/** A plain file at `path` (true), nothing there (false), or an error for anything else. */
export async function plainFile(path: string): Promise<boolean> {
  try {
    if ((await lstat(path)).isFile()) return true;
    throw new Error(`Refusing a linked/non-file Winix executable: ${path}`);
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code !== "ENOENT") throw error;
    return false;
  }
}

/** Write a file Winix generates, refusing to replace one it didn't. */
export async function writeGenerated(path: string, content: string, what: string): Promise<void> {
  try {
    const stat = await lstat(path);
    if (!stat.isFile() || !(await readFile(path, "utf8")).includes("Generated by Winix bootstrap")) {
      throw new Error(`Refusing to overwrite an unrecognized ${what}: ${path}`);
    }
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code !== "ENOENT") throw error;
  }
  await writeFile(path, content, { mode: 0o755 });
}

export interface HomeEnvironment {
  platform: NodeJS.Platform;
  env: NodeJS.ProcessEnv;
  home: string;
}

const currentEnvironment = (): HomeEnvironment => ({ platform: process.platform, env: process.env, home: homedir() });

/** Where the per-user installation lives. */
export function winixHome(environment: HomeEnvironment = currentEnvironment()): string {
  if (environment.platform === "win32") {
    const local = environment.env.LOCALAPPDATA;
    if (!local) throw new Error("LOCALAPPDATA is not set; cannot find the Winix installation folder");
    return join(local, "Winix");
  }
  return join(environment.env.XDG_DATA_HOME || join(environment.home, ".local", "share"), "winix");
}

/** The folder of the `winix` command. */
export function commandDirectory(environment: HomeEnvironment = currentEnvironment()): string {
  return environment.platform === "win32" ? join(winixHome(environment), "bin") : join(environment.home, ".local", "bin");
}

// ---------------------------------------------------------------------------
// The checkout `winix switch` uses outside any project

function checkoutFile(environment?: HomeEnvironment): string {
  return join(winixHome(environment), "checkout");
}

export async function rememberCheckout(configDir: string, environment?: HomeEnvironment): Promise<void> {
  const home = winixHome(environment);
  await assertPlainDirectories([home]);
  await mkdir(home, { recursive: true });
  await writeFile(checkoutFile(environment), `${resolve(configDir)}\n`);
}

/** The remembered config directory, if it still holds a config. */
export function rememberedCheckout(environment?: HomeEnvironment): string | undefined {
  try {
    const directory = readFileSync(checkoutFile(environment), "utf8").trim();
    return directory && existsSync(join(directory, "winix.config.ts")) ? directory : undefined;
  } catch {
    return undefined;
  }
}

