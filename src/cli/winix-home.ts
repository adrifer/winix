// The command

/** %LOCALAPPDATA%\Winix\bin\winix.cmd: runs the installed Winix's router. */
export function windowsCommandShim(executable: string): string {
  return ["@echo off", "rem Generated by Winix bootstrap", `"${executable}" run %*`, "exit /b %ERRORLEVEL%", ""].join("\r\n");
}

/** ~/.local/bin/winix. */
export function linuxCommandShim(executable: string): string {
  return `#!/usr/bin/env bash\n${GENERATED}\nexec ${shellQuote(executable)} run "$@"\n`;
}

/** Adds a directory to the user PATH, keeping %VARIABLE% entries unexpanded, and notifies running apps. */
export function userPathScript(directory: string): string {
  return `$ErrorActionPreference = 'Stop'
$dir = '${directory.replaceAll("'", "''")}'
$key = [Microsoft.Win32.Registry]::CurrentUser.OpenSubKey('Environment', $true)
$changed = $false
try {
  $current = [string]$key.GetValue('Path', '', [Microsoft.Win32.RegistryValueOptions]::DoNotExpandEnvironmentNames)
  $kind = if ($null -ne $key.GetValue('Path')) { $key.GetValueKind('Path') } else { [Microsoft.Win32.RegistryValueKind]::ExpandString }
  $entries = @($current -split ';' | Where-Object { $_ })
  if (-not ($entries | Where-Object { $_.TrimEnd('\\') -ieq $dir.TrimEnd('\\') })) {
    $key.SetValue('Path', (@($entries) + $dir) -join ';', $kind)
    $changed = $true
  }
} finally { $key.Dispose() }
# Setting a user variable broadcasts WM_SETTINGCHANGE, so new terminals see the PATH.
if ($changed) { [Environment]::SetEnvironmentVariable('WINIX_PATH_REFRESH', $null, 'User') }
`;
}

export interface InstallCommandDeps {
  environment: HomeEnvironment;
  /** The running Winix: the executable (Windows) or the wrapper (Linux), and its version. */
  running: { executable: string; version: string };
  arch: string;
  nixos: boolean;
  exec: (command: string, args: string[]) => string;
  /** Put a directory on the Windows user PATH. */
  addToPath(directory: string): void;
  log(line: string): void;
}

function defaultInstallDeps(): InstallCommandDeps {
  const runtime = standaloneRuntime();
  if (!runtime) throw new Error("winix install command needs the standalone Winix executable (npm installs have npx winix).");
  return {
    environment: currentEnvironment(),
    running: { executable: process.env.WINIX_STANDALONE_EXECUTABLE ?? process.execPath, version: runtime.version },
    arch: process.arch,
    nixos: existsSync("/etc/NIXOS"),
    exec: defaultExec,
    addToPath: (directory) => {
      execFileSync("powershell.exe", [
        "-NoLogo", "-NoProfile", "-NonInteractive", "-EncodedCommand", Buffer.from(userPathScript(directory), "utf16le").toString("base64"),
      ], { stdio: ["ignore", "ignore", "pipe"], timeout: 60000 });
    },
    log: (line) => console.log(line),
  };
}

const same = (a: string, b: string, platform: NodeJS.Platform) =>
  platform === "win32" ? resolve(a).toLowerCase() === resolve(b).toLowerCase() : resolve(a) === resolve(b);

/** The running Winix, copied into <home>/runtime/<version> unless it already runs from there. */
async function installRuntime(deps: InstallCommandDeps): Promise<string> {
  const { environment, running } = deps;
  const home = winixHome(environment);
  const runtime = join(home, "runtime");
  const folder = join(runtime, running.version);
  await assertPlainDirectories([home, runtime, folder]);
  await mkdir(folder, { recursive: true });
  if (environment.platform === "win32") {
    const target = join(folder, "winix.exe");
    if (!same(running.executable, target, "win32")) await copyAtomically(running.executable, target);
    return target;
  }
  const wrapper = join(folder, "winix");
  if (same(running.executable, wrapper, environment.platform)) return wrapper;
  // Running through another wrapper: its binary sits next to it.
  const sibling = join(dirname(running.executable), "winix.bin");
  const binary = existsSync(sibling) ? sibling : running.executable;
  await copyAtomically(binary, join(folder, "winix.bin"), 0o755);
  await writeLinuxWrapper(folder, deps.arch, deps.nixos, deps.exec);
  const reported = deps.exec(wrapper, ["--version"]).trim();
  if (reported !== running.version) throw new Error(`Installed Winix reports ${reported || "nothing"}, expected ${running.version}`);
  return wrapper;
}

/** Copy through a temporary file, so a half-written executable is never in place. */
async function copyAtomically(source: string, target: string, mode?: number): Promise<void> {
  await plainFile(target); // refuses a link or directory in the way
  const temporary = `${target}.${process.pid}.copy`;
  try {
    await copyFile(source, temporary);
    if (mode !== undefined) await chmod(temporary, mode);
    await rename(temporary, target);
  } finally {
    await rm(temporary, { force: true });
  }
}

/** Remove older installed versions, keeping `keep` (best effort: one in use stays). */
async function pruneInstalled(environment: HomeEnvironment, keep: string[]): Promise<void> {
  const runtime = join(winixHome(environment), "runtime");
  let names: string[];
  try { names = await readdir(runtime); } catch { return; }
  for (const name of names) {
    const path = join(runtime, name);
    if (!/^\d+\.\d+\.\d+(?:-preview\.\d+)?$/.test(name) || keep.some((kept) => same(kept, path, environment.platform))) continue;
    try {
      if ((await lstat(path)).isDirectory()) await rm(path, { recursive: true, force: true });
    } catch { /* in use: removed after a later install */ }
  }
}

/**
 * `winix install command`: install the running Winix for this user and put a
 * `winix` command on PATH that runs it. Returns the command's path.
 */
export async function installWinixCommand(deps: InstallCommandDeps = defaultInstallDeps()): Promise<string> {
  const { environment } = deps;
  const installed = await installRuntime(deps);
  const bin = commandDirectory(environment);
  await assertPlainDirectories([dirname(bin), bin]);
  await mkdir(bin, { recursive: true });
  const windows = environment.platform === "win32";
  const command = join(bin, windows ? "winix.cmd" : "winix");
  await writeGenerated(command, windows ? windowsCommandShim(installed) : linuxCommandShim(installed), "winix command");
  await pruneInstalled(environment, [dirname(installed), dirname(deps.running.executable)]);
  if (windows) {
    deps.addToPath(bin);
    deps.log(`Command: winix ${deps.running.version} (${command}, on your user PATH; open a new terminal to use it).`);
  } else {
    const path = environment.env.PATH ?? "";
    const onPath = path.split(delimiter).some((entry) => entry.replace(/[\\/]+$/, "") === bin);
    deps.log(onPath
      ? `Command: winix ${deps.running.version} (${command}).`
      : `Command: winix ${deps.running.version} (${command}). ~/.local/bin is not on PATH: add it in your shell or config, e.g. home.path(nix.homePath(".local/bin")).`);
  }
  return command;
}
