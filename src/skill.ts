export function authoringApiPaths(): string[] {
  return [
    ...CORE_AUTHORING_API,
    ...collectApiPaths("rawModule", rawModule),
    ...collectApiPaths("account", account),
    ...collectApiPaths("platforms", platforms),
    ...collectApiPaths("nix", nix),
    ...collectApiPaths("overlay", overlay),
    ...collectApiPaths("home", home),
    ...collectApiPaths("nixos", nixos),
    ...collectApiPaths("darwin", darwin),
    ...collectApiPaths("windows", windows),
  ];
}

function collectApiPaths(prefix: string, value: object): string[] {
  const paths = [prefix];
  for (const [key, child] of Object.entries(value)) {
    const path = `${prefix}.${key}`;
    paths.push(path);
    if (
      ((typeof child === "object" && child !== null) || typeof child === "function") &&
      !isNixExpr(child)
    ) {
      paths.push(...collectApiPaths(path, child as object).slice(1));
    }
  }
  return paths;
}

function isNixExpr(value: unknown): boolean {
  return (
    typeof value === "object" &&
    value !== null &&
    "__winixNixExpr" in value
  );
}
