/**
 * Bundle generated NixOS types into a single self-contained .d.ts file
 * that can be shipped with the package and auto-referenced.
 */
import { readFile, writeFile, mkdir } from "node:fs/promises";
import { join } from "node:path";

const inputDir = process.argv[2] || "test-config/.winix/types/generated";
const outputFile = process.argv[3] || "types/bundled/nixos-unstable.d.ts";

const nixosTypes = await readFile(join(inputDir, "nixos.d.ts"), "utf-8");
const indexTypes = await readFile(join(inputDir, "index.d.ts"), "utf-8");

// Strip the import lines from nixos.d.ts (they reference "winix" and "winix/types")
// and from index.d.ts (it imports from "./nixos" which won't exist standalone)
const nixosBody = nixosTypes
  .split("\n")
  .filter(line => !line.startsWith("import type"))
  .join("\n");

// Extract just the declare module blocks from index.d.ts
const declareModuleBlocks = indexTypes
  .split("\n")
  .filter(line => !line.startsWith("import type") && !line.startsWith("export type"))
  .join("\n")
  .trim();

const output = [
  "// Bundled NixOS option types (nixos-unstable snapshot).",
  "// Generated by winix. Provides typed autocomplete for nixos.program() and nixos.service() helpers.",
  "// To update: run `winix types generate` in your project.",
  "",
  'import type { NixExpr } from "winix";',
  'import type { PackageRef } from "winix/types";',
  "",
  nixosBody.trim(),
  "",
  declareModuleBlocks,
  "",
].join("\n");

await mkdir(join(outputFile, ".."), { recursive: true });
await writeFile(outputFile, output);
console.log(`✓ Bundled types written to ${outputFile} (${(output.length / 1024).toFixed(0)} KB)`);
