const HEADER = "<!-- Generated by scripts/api-docs.mjs from the source's types and doc comments. Edit those, then run npm run api-docs. -->";
const MAX_OPTIONS = 60;

function program() {
  const configFile = ts.readConfigFile(join(ROOT, "tsconfig.json"), ts.sys.readFile);
  const parsed = ts.parseJsonConfigFileContent(configFile.config, ts.sys, ROOT);
  return ts.createProgram([ENTRY], { ...parsed.options, noEmit: true });
}

const inSource = (node) => {
  const file = node?.getSourceFile?.().fileName;
  return Boolean(file) && resolve(file).startsWith(SOURCE + sep) && !resolve(file).includes(`${sep}types${sep}bundled`);
};

/**
 * Types whose options we list. Not the hand-written mirrors of NixOS, Home
 * Manager and nix-darwin options (src/types/nixos.ts, ...): those options are
 * documented upstream, and each page links there.
 */
const MIRRORS = ["nixos.ts", "darwin.ts", "home.ts", "programs.ts", "common.ts"].map((file) => join(SOURCE, "types", file));
const expandable = (node) => inSource(node) && !MIRRORS.includes(resolve(node.getSourceFile().fileName));

/** Doc text of a symbol or signature, with its @example blocks, and {@link X} written as `X`. */
function docs(checker, item) {
  const parts = [ts.displayPartsToString(item.getDocumentationComment(checker)).trim()];
  const tags = item.getJsDocTags?.(checker) ?? [];
  for (const tag of tags) {
    if (tag.name !== "example") continue;
    const example = ts.displayPartsToString(tag.text).trim();
    parts.push(example.startsWith("```") ? example : `\`\`\`ts\n${example}\n\`\`\``);
  }
  return parts.filter(Boolean).join("\n\n")
    .replace(/\{@link\s+([^}|\s]+)(?:\s*\|\s*([^}]+))?\}/g, (_m, target, label) => `\`${(label ?? target).trim()}\``);
}

/** One line for a table cell: no code blocks, no line breaks, pipes escaped. */
function cell(text) {
  return text.replace(/```[\s\S]*?```/g, "").replace(/\s*\n\s*/g, " ").replace(/\|/g, "\\|").trim();
}

/** Inline code inside a table cell. */
function codeCell(text) {
  return code(text).replace(/\|/g, "\\|");
}

function typeText(checker, type) {
  if (type.flags & ts.TypeFlags.TypeParameter) {
    const constraint = checker.getBaseConstraintOfType(type);
    if (constraint && !(constraint.flags & ts.TypeFlags.Unknown)) type = constraint;
  }
  // Optional members already say "?"; "| undefined" only adds noise.
  return checker.typeToString(type, undefined, ts.TypeFormatFlags.NoTruncation | ts.TypeFormatFlags.UseAliasDefinedOutsideCurrentScope)
    .replace(/ \| undefined\b/g, "");
}

function code(text) {
  return `\`${text.replace(/`/g, "'")}\``;
}

/** Object types (from our own source) inside a type, to list as options. */
function optionTypes(checker, type) {
  const parts = type.isUnion() ? type.types : [type];
  return parts.filter((part) => {
    if (part.getCallSignatures().length > 0) return false;
    if (!(part.flags & ts.TypeFlags.Object) || checker.isArrayType(part) || checker.isTupleType(part)) return false;
    const properties = part.getProperties().filter((property) => !property.name.startsWith("__"));
    if (properties.length === 0 || properties.length > MAX_OPTIONS) return false;
    // Only declared properties of Winix's own types: never NixOS/Home Manager/
    // nix-darwin option types, nor the generated keys of a Record<...>.
    return properties.every((property) => {
      const declarations = property.declarations ?? [];
      return declarations.length > 0 && declarations.every((declaration) => expandable(declaration) && !ts.isMappedTypeNode(declaration));
    });
  });
}

/** Types that are values from other helpers, not options to fill in. */
const OPAQUE = new Set([
  "ResourceHandle", "Fragment", "HostDef", "NixExpr", "AccountUserRef", "LazyFragment", "PlatformLazyFragment", "WinKnownFolder",
]);

/** Heading anchor, as Starlight and GitHub slug it. */
function anchor(path) {
  return `#${`${path}()`.toLowerCase().replace(/[^a-z0-9 _-]/g, "").replace(/ /g, "-")}`;
}

/** Options tables of a parameter. `shown` (per page) links a type already listed instead of repeating it. */
function optionsTables(checker, label, type, node, depth, seen, missing, where, shown) {
  const lines = [];
  for (const part of optionTypes(checker, type)) {
    const name = part.aliasSymbol?.name ?? part.symbol?.name;
    if (OPAQUE.has(name) || seen.has(part)) continue;
    seen.add(part);
    const first = shown.get(part);
    if (first && first !== where) {
      lines.push("", `**${label}**: the same options as [${first}()](${anchor(first)}).`);
      continue;
    }
    shown.set(part, where);
    const rows = [];
    const nested = [];
    for (const property of part.getProperties()) {
      if (property.name.startsWith("__")) continue;
      const declaration = property.valueDeclaration ?? property.declarations?.[0];
      const propertyType = checker.getTypeOfSymbolAtLocation(property, declaration ?? node);
      const optional = (property.flags & ts.SymbolFlags.Optional) !== 0;
      const text = docs(checker, property);
      if (!text) missing.push(`${where}: ${label} option ${property.name}`);
      rows.push(`| ${codeCell(property.name + (optional ? "?" : ""))} | ${codeCell(typeText(checker, checker.getNonNullableType(propertyType)))} | ${cell(text)} |`);
      if (depth < 2) nested.push([property.name, checker.getNonNullableType(propertyType)]);
    }
    lines.push("", `**${label}**`, "", "| Option | Type | Description |", "| --- | --- | --- |", ...rows);
    for (const [property, propertyType] of nested) {
      lines.push(...optionsTables(checker, `\`${property}\``, propertyType, node, depth + 1, seen, missing, where, shown));
    }
  }
  return lines;
}

/**
 * A signature's parameters as written: a rest parameter typed as a labelled
 * tuple (PlatformFactory's `...args: [opts?: X]`) becomes its elements.
 */
function parametersOf(checker, signature, fallback) {
  const result = [];
  for (const parameter of signature.parameters) {
    const declaration = parameter.valueDeclaration;
    const rest = Boolean(declaration && ts.isParameter(declaration) && declaration.dotDotDotToken);
    const optional = Boolean(declaration && ts.isParameter(declaration) && (declaration.questionToken || declaration.initializer));
    const type = checker.getTypeOfSymbolAtLocation(parameter, declaration ?? fallback);
    if (rest && checker.isTupleType(type)) {
      const target = type.target;
      checker.getTypeArguments(type).forEach((element, index) => {
        const label = target.labeledElementDeclarations?.[index]?.name?.getText();
        const elementOptional = Boolean(target.elementFlags[index] & ts.ElementFlags.Optional);
        result.push({ name: label ?? `${parameter.name}${index}`, type: elementOptional ? checker.getNonNullableType(element) : element, optional: elementOptional, rest: false });
      });
      continue;
    }
    result.push({ name: parameter.name, type: optional ? checker.getNonNullableType(type) : type, optional, rest });
  }
  return result;
}

function signatureText(checker, path, signature, fallback) {
  const params = parametersOf(checker, signature, fallback)
    .map((parameter) => `${parameter.rest ? "..." : ""}${parameter.name}${parameter.optional ? "?" : ""}: ${typeText(checker, parameter.type)}`);
  return `${path}(${params.join(", ")}): ${typeText(checker, signature.getReturnType())}`;
}

const RETURNS = {
  ResourceHandle: "Returns a handle, for another resource's `dependsOn`.",
  Fragment: "Returns a fragment: declared when called through a feature's or host's namespace, otherwise return it.",
  NixExpr: "Returns a Nix expression, usable wherever a value goes.",
};

function isNamespace(checker, type) {
  if (type.getCallSignatures().length > 0) return true;
  const properties = type.getProperties();
  if (properties.length === 0 || !properties.some((property) => (property.declarations ?? []).some(inSource))) return false;
  // A namespace of helpers: some members are callable (NixExpr values are not).
  return properties.some((property) => {
    const declaration = property.valueDeclaration ?? property.declarations?.[0];
    return declaration && checker.getTypeOfSymbolAtLocation(property, declaration).getCallSignatures().length > 0;
  });
}

/**
 * A member's section, and its members' sections. `flat` (a page's only
 * export): no heading for the namespace itself, its members are top-level.
 */
function documentMember(checker, path, symbol, node, level, missing, flat, shown) {
  const declaration = symbol.valueDeclaration ?? symbol.declarations?.[0] ?? node;
  const type = checker.getTypeOfSymbolAtLocation(symbol, declaration);
  const heading = "#".repeat(Math.min(level, 4));
  const lines = [];
  const signatures = type.getCallSignatures();
  const own = docs(checker, symbol);
  if (signatures.length > 0) {
    lines.push("", `${heading} ${path}()`);
    const description = own || signatures.map((signature) => docs(checker, signature)).find(Boolean) || "";
    if (!description) missing.push(path);
    if (description) lines.push("", description);
    lines.push("", "```ts", ...signatures.map((signature) => signatureText(checker, path, signature, declaration)), "```");
    const seen = new Set();
    for (const signature of signatures) {
      for (const parameter of parametersOf(checker, signature, declaration)) {
        const parameterType = checker.getNonNullableType(parameter.type);
        lines.push(...optionsTables(checker, `\`${parameter.name}\``, parameterType, declaration, 1, seen, missing, path, shown));
        // A function parameter returning options (account.user's factory): list what it returns.
        for (const callback of parameterType.getCallSignatures()) {
          const returned = checker.getNonNullableType(callback.getReturnType());
          lines.push(...optionsTables(checker, `\`${parameter.name}\` returns`, returned, declaration, 1, seen, missing, path, shown));
        }
      }
    }
    const returned = signatures[0].getReturnType();
    const returnName = returned.aliasSymbol?.name ?? returned.symbol?.name;
    if (RETURNS[returnName]) lines.push("", RETURNS[returnName]);
  } else if (isNamespace(checker, type)) {
    if (!flat) lines.push("", `${heading} ${path}`);
    if (own) lines.push("", own);
  } else {
    lines.push("", `${heading} ${path}`, "", "```ts", `${path}: ${typeText(checker, type)}`, "```");
    if (!own) missing.push(path);
    if (own) lines.push("", own);
    return lines;
  }
  if (isNamespace(checker, type)) {
    for (const property of type.getProperties()) {
      if (property.name.startsWith("__") || property.name === "prototype") continue;
      lines.push(...documentMember(checker, `${path}.${property.name}`, property, declaration, flat ? level : level + 1, missing, false, shown));
    }
  }
  return lines;
}

/** Every page's Markdown, and the members without a doc comment. */
export function generateApiDocs() {
  const tsProgram = program();
  const checker = tsProgram.getTypeChecker();
  const entry = checker.getSymbolAtLocation(tsProgram.getSourceFile(ENTRY));
  const exports = new Map(checker.getExportsOfModule(entry).map((symbol) => [symbol.name, symbol]));
  const files = new Map();
  const missing = [];
  const listed = new Set(PAGES.flatMap((page) => page.exports));
  for (const [name, exported] of exports) {
    const resolved = exported.flags & ts.SymbolFlags.Alias ? checker.getAliasedSymbol(exported) : exported;
    if ((resolved.flags & ts.SymbolFlags.Value) !== 0 && !listed.has(name)) {
      missing.push(`unlisted export: ${name}`);
    }
  }
  PAGES.forEach((page, index) => {
    const lines = [
      "---", `title: ${JSON.stringify(page.title)}`, `description: ${JSON.stringify(page.description)}`,
      "sidebar:", `  order: ${index + 1}`, "---", "", HEADER, "", `# ${page.title}`, "", page.intro,
    ];
    const shown = new Map();
    for (const name of page.exports) {
      let symbol = exports.get(name);
      if (!symbol) throw new Error(`@adrifer/winix does not export ${name}`);
      if (symbol.flags & ts.SymbolFlags.Alias) symbol = checker.getAliasedSymbol(symbol);
      lines.push(...documentMember(checker, name, symbol, symbol.valueDeclaration, 2, missing, page.exports.length === 1, shown));
    }
    // Doc comments from CRLF checkouts carry "\r": the output is LF everywhere.
    files.set(page.file, `${lines.join("\n").replace(/\r\n?/g, "\n").replace(/\n{3,}/g, "\n\n")}\n`);
  });
  files.set("README.md", [
    "---", 'title: "API"', 'description: "Every helper and option, generated from the source."', "sidebar:", "  label: Overview", "  order: 0", "---", "",
    HEADER, "", "# API", "",
    "Every function and option you can call from a config, generated from the source's types and doc comments.",
    "The [reference](../reference/config.md) explains them with examples; your editor shows the same text on hover.", "",
    "| Page | |", "| --- | --- |",
    ...PAGES.map((page) => `| [${page.title}](${page.file}) | ${page.description} |`), "",
  ].join("\n"));
  return { files, missing };
}

function main() {
  const check = process.argv.includes("--check");
  const { files, missing } = generateApiDocs();
  if (check) {
    const stale = [...files].filter(([file, content]) => !existsSync(join(OUTPUT, file)) ||
      readFileSync(join(OUTPUT, file), "utf8").replace(/\r\n/g, "\n") !== content);
    if (stale.length > 0) {
      console.error(`docs/api is out of date (${stale.map(([file]) => file).join(", ")}): run npm run api-docs.`);
      process.exit(1);
    }
    console.log("docs/api is up to date.");
    return;
  }
  if (existsSync(OUTPUT)) for (const file of readdirSync(OUTPUT)) if (!files.has(file)) rmSync(join(OUTPUT, file));
  mkdirSync(OUTPUT, { recursive: true });
  for (const [file, content] of files) writeFileSync(join(OUTPUT, file), content);
  console.log(`Wrote ${files.size} pages to ${relative(ROOT, OUTPUT)}.`);
  if (missing.length > 0) console.log(`${missing.length} members without a doc comment:\n  ${missing.join("\n  ")}`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
