#!/usr/bin/env node
// Generates the API reference (docs/api/*.md) from the public SDK's types and
// doc comments, using the TypeScript compiler. One page per namespace; each
// call gets its signature, its doc comment and its options, expanded in place.
//
//   npm run api-docs           write docs/api
//   npm run api-docs -- --check   fail when docs/api is out of date
//
// tests/api-docs.test.ts runs the same check and lists undocumented members.

